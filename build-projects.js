  const dir = path.join(root, p.folder);
  const images = fs.existsSync(dir)
    ? fs.readdirSync(dir).filter(function (f) { return ok.test(f); }).sort().map(function (f) {
        return 'images/' + p.folder + '/' + f;
      })
    : [];
  return Object.assign({}, p, { images: images });
